-- Q25. Find products whose revenue is greater than average product revenue.
select p.product_id, p.product_name, sum(o.quantity * p.price) as Total_revenue
from products p
join orders o 
on p.product_id = o.product_id
group by p.product_id, p.product_name
having sum(o.quantity * p.price) > (
select avg(Product_revenue)
from (
select sum(o2.quantity * p2.price) as Product_revenue
from products p2
join orders o2
on p2.product_id = o2.product_id
group by p2.product_id
) as Revenue_table
);

