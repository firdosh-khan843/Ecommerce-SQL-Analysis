-- Q27. Find the top 3 customers using RANK().
select * 
from (
 select c.customer_id, c.customer_name, sum(o.quantity * p.price) as Total_spending,
 rank() over(
  order by sum(o.quantity * p.price) desc
  ) as Customer_rank
from customers c
join orders o 
on c.customer_id = o.customer_id
join products p 
on o.product_id = p.product_id
group by c.customer_id, c.customer_name
) as Ranked_customer
where Customer_rank <= 3;

-- Q28. Find the highest-revenue product in each category.
select *
from (
 select p.category, p.product_id, p.product_name, sum(o.quantity * p.price) as Total_revenue,
 rank() over(
 partition by p.category
 order by sum(o.quantity * p.price) desc
) as Revenue_rank
from products p
join orders o 
on p.product_id = o.product_id
group by  p.category, p.product_id, p.product_name
) as Ranked_products
where Revenue_rank = 1;

